    entities,
    setEntities,
    activeEntityIndex,
    setActiveEntityIndex,
    currentTurnRound,
    setCurrentTurnRound,
    isBattleOver,
    setIsBattleOver,
    setIsVictoryScreenVisible,
    grid,
    torches,
    biome,
    weather,
    isNight,
