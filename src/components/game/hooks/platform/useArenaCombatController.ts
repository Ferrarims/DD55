  useMonsterTurnAI({
    activeEntity,
    activeEntityIndex,
    isBattleOver,
    entities,
    entitiesRef,
    setEntities,
    grid,
    biome,
    isNight,
    torches,
    character,
    activeLargeForm,
    currentSelectedAttack,
    getHeroLightRadiusInCells,
    advanceTurn,
    addCombatLog,
    triggerAttackVisualEffect,
    setLatestRoll,
    processDamageAndCheckKill,
    checkGridTriggers,
    onTriggerOpportunityAttack: setPendingOpportunityAttack,
  });

  // Teclado
  useGameKeyboard({
    isHeroTurn,
    isBattleOver,
    activeEntity,
    grid,
    entities,
    moveHeroDirection,
  });

