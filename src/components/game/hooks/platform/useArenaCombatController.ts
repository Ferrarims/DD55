    checkAmmunitionRequirement,
    getCharacterAmmoCount,
    consumeAmmunition,
    getActiveFeats,
    getHeroLightRadiusInCells,
    isEntityVisible,
    setRollAdvantageState,
    setPendingGoliathHitInfo,
    setTargetCandidates,
    setPendingAttackInfo,
    setShowTargetModal,
    setShowAttackModal,
    setPendingHalflingLuckInfo,
